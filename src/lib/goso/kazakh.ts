const NORMALIZED_TO_RU = new Map<string, string>();
for (const [ru, kz] of Object.entries(GOSO_SUBJECT_KZ)) {
  NORMALIZED_TO_RU.set(ru.toLowerCase(), ru);
  NORMALIZED_TO_RU.set(kz.toLowerCase(), ru);
}
for (const [alias, ru] of Object.entries(EXTRA_ALIASES_TO_RU)) {
  NORMALIZED_TO_RU.set(alias.toLowerCase(), ru);
}

/** Возвращает каноническое русское название предмета из `data/goso_official.json` по русскому или казахскому названию. */
export function resolveRussianSubjectName(input: string): string | null {
  const clean = input.trim().toLowerCase().replace(/\s+/g, " ");
  if (!clean) return null;
  return NORMALIZED_TO_RU.get(clean) ?? null;
}

/** Возвращает официальное казахское название предмета ГОСО (или исходное, если соответствие не требуется). */
export function subjectNameKz(subjectRu: string): string {
  const canonical = resolveRussianSubjectName(subjectRu);
  if (canonical && GOSO_SUBJECT_KZ[canonical]) return GOSO_SUBJECT_KZ[canonical];
  return GOSO_SUBJECT_KZ[subjectRu.trim()] ?? subjectRu;
}

