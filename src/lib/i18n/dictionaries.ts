export const dictionaries: Record<Locale, Dict> = { ru, kk };

export function isLocale(value: unknown): value is Locale {
  return value === "ru" || value === "kk";
}

/**
 * Подстановка значений в шаблон словаря: `{n}`, `{percent}`, `{subject}`.
 * Неизвестный плейсхолдер остаётся как есть — пропуск должен быть виден
 * в интерфейсе, а не превращаться в пустую строку.
 */
export function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match,
  );
}

/** Значение словаря по точечному пути: `resolve(t, "planEditor.save.save")`. */
export function resolve(t: Dict, path: string): string | undefined {
  const value = path.split(".").reduce<unknown>(
    (node, key) => (node && typeof node === "object" ? (node as Record<string, unknown>)[key] : undefined),
    t,
  );
  return typeof value === "string" ? value : undefined;
}
