/**
 * Рабочая инструкция агента для Kundelik.kz (электронный журнал и дневник РК).
 *
 * Как и для BilimClass, это операционный playbook: агент опирается только на
 * текущий экран, никогда не вводит логин/пароль/ЭЦП самостоятельно и соблюдает
 * политики подтверждения в computer/safety.ts.
 */
const KUNDELIK_HOST = /(^|\.)kundelik\.kz$/i;

export function isKundelikContext(goal: string, url: string): boolean {
  let onKundelik = false;
  try {
    onKundelik = KUNDELIK_HOST.test(new URL(url).hostname);
  } catch {
    // Некорректный URL не активирует навык.
  }

  return (
    onKundelik ||
    /kundelik|кунделик|күнделік|поурочн.{0,20}планирован.{0,20}кунделик/i.test(goal)
  );
}

