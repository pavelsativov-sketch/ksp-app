/**
 * Рабочая инструкция агента для BilimClass.
 *
 * Это предметный playbook, а не дообучение весов модели: факты о текущем
 * интерфейсе всегда проверяются по экрану, а изменения защищены политиками
 * подтверждения в computer/safety.ts.
 */
const BILIMCLASS_HOST = /(^|\.)bilimclass\.kz$/i;

export function isBilimClassContext(goal: string, url: string): boolean {
  let onBilimClass = false;
  try {
    onBilimClass = BILIMCLASS_HOST.test(new URL(url).hostname);
  } catch {
    // Невалидный адрес не включает правила домена.
  }

  return (
    onBilimClass ||
    /bilim\s*class|билим\s*класс|bilimclass/i.test(goal)
  );
}

