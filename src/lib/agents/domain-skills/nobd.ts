/**
 * Рабочая инструкция агента для НОБД / ҰБДҚ (Национальная образовательная база данных РК).
 *
 * НОБД содержит государственную статистическую отчётность и чувствительные
 * персональные записи (ИИН, приказы о движении контингента, карточки педагогов),
 * поэтому действует усиленный режим чтения и подтверждения.
 */
const NOBD_HOST = /(^|\.)(nobd\.edu\.kz|nobd\.iac\.kz|e\.edu\.kz)$/i;

export function isNobdContext(goal: string, url: string): boolean {
  let onNobd = false;
  try {
    onNobd = NOBD_HOST.test(new URL(url).hostname);
  } catch {
    // Некорректный URL не активирует навык.
  }

  return (
    onNobd ||
    /(?<![\p{L}\p{N}_])(нобд|ұбдқ|nobd)(?![\p{L}\p{N}_])|национальн.{0,20}образовательн.{0,20}баз/iu.test(goal)
  );
}

