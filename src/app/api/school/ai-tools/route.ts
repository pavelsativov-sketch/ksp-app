import { NextResponse } from "next/server";
import { requireApiAuth } from "@/lib/api-auth";
import { checkRateLimitAsync } from "@/lib/rate-limit";
import { executeWithFallback } from "@/lib/ai/providers";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

export async function POST(req: Request) {
  const auth = await requireApiAuth();
  if (auth.response) return auth.response;

  const rl = await checkRateLimitAsync(`school:ai-tools:${auth.user.id}`, 30, 60_000);
  if (!rl.ok) {
    return NextResponse.json({ error: "Слишком много запросов. Подождите минуту." }, { status: 429 });
  }

  let body: {
    tool: "sor-soch" | "vsk-spravka" | "characteristic" | "homeroom" | "iom";
    params: Record<string, unknown>;
  };

  try {
    body = await req.json();
  } catch {
    return NextResponse.json({ error: "Некорректный JSON" }, { status: 400 });
  }

  const { tool } = body;
  const params: Record<string, unknown> =
    body.params && typeof body.params === "object"
      ? body.params
      : (body as unknown as Record<string, unknown>);
  if (!tool) {
    return NextResponse.json({ error: "Не указан инструмент" }, { status: 400 });
  }

  let systemPrompt = "";
  let userPrompt = "";

  if (tool === "sor-soch") {
    const subject = String(params.subject || "Предмет");
    const grade = String(params.grade || "7");
    const quarter = String(params.quarter || "1");
    const workType = String(params.workType || "СОР №1");
    const maxScore = Number(params.maxScore || 20);
    const scoresRaw = String(params.scores || "");
    const topic = String(params.topic || "");

    systemPrompt = `Ты — ведущий методист-эксперт школ Республики Казахстан (МОН / МП РК). 
Ты составляешь официальный педагогический анализ результатов суммативного оценивания (СОР / СОЧ) в строгом соответствии с критериальной системой оценивания РК.
Документ должен быть полностью готов для сдачи завучу и включения в портфолио педагога.`;

    userPrompt = `Составь полный педагогический анализ результатов суммативного оценивания:
- Предмет: ${subject}
- Класс: ${grade}
- Четверть: ${quarter}
- Вид работы: ${workType}
- Максимальный балл: ${maxScore}
${topic ? `- Тема / разделы: ${topic}` : ""}
- Исходные баллы учащихся класса (через запятую или список): ${scoresRaw || "18, 15, 20, 14, 12, 19, 16, 11, 20, 17, 13, 8, 15, 17, 16"}

В отчёте обязательно предоставь:
1. Статистические показатели:
   - Всего учащихся писали работу
   - Качество знаний (% учащихся с оценками «4» и «5» / балл >= 65%)
   - Успеваемость (% учащихся без двойки / балл >= 40%)
   - Средний балл
2. Анализ по уровням мыслительной деятельности:
   - Знание и понимание (доля освоения)
   - Применение (доля освоения)
   - Навыки высокого порядка / анализ и синтез (доля освоения)
3. Достигнутые цели обучения и сильные стороны класса.
4. Выявленные типичные затруднения и пробелы учащихся (с указанием конкретных понятий/правил).
5. Причины допущенных ошибок.
6. Конкретный план коррекционной работы и методические рекомендации для учителя (темы для повторения, дифференцированные задания, график консультаций).

Форматируй текст аккуратно с заголовками, пунктами и табличными данными в Markdown.`;

  } else if (tool === "vsk-spravka") {
    const inspectionType = String(params.inspectionType || "Посещение уроков");
    const target = String(params.target || "Учителя предметной кафедры");
    const date = String(params.date || new Date().toLocaleDateString("ru-RU"));
    const purpose = String(params.purpose || "Контроль соблюдения требований ГОСО");
    const notes = String(params.notes || "");

    systemPrompt = `Ты — опытный заместитель директора по учебно-воспитательной работе (завуч) школы Республики Казахстан.
Ты составляешь официальные аналитические справки по итогам внутришкольного контроля (ВШК) в соответствии с Типовыми правилами деятельности организаций образования РК.
Стиль — строго деловой, объективный, доказательный, профессиональный.`;

    userPrompt = `Составь официальную аналитическую справку по итогам внутришкольного контроля:
- Направление проверки: ${inspectionType}
- Объект контроля: ${target}
- Сроки/Дата проверки: ${date}
- Цель контроля: ${purpose}
${notes ? `- Фактические наблюдения / замечания / сильные стороны: ${notes}` : ""}

Структура справки:
1. Шапка документа: «СПРАВКА по итогам внутришкольного контроля»
2. Вводная часть: Основание проверки (план ВШК), сроки, цель, состав проверяющих, методы контроля.
3. Констатирующая часть (Анализ увиденного):
   - Положительные аспекты и методические успехи
   - Выявленные недочёты и отклонения от требований
   - Конкретные факты и примеры
4. Выводы: Общая оценка результативности по проверяемому направлению.
5. Рекомендации и управленческие решения:
   - Кому адресованы (учителям-предметникам, классным руководителям, руководителю МО)
   - Конкретные сроки устранения замечаний
   - Повестка рассмотрения (на заседании МО / совещании при завуче / педсовете).

Форматируй в чистый Markdown, готовый к распечатке.`;

  } else if (tool === "characteristic") {
    const studentName = String(params.studentName || "Учащийся");
    const grade = String(params.grade || "7 класс");
    const purpose = String(params.purpose || "Для комиссии ПМПК");
    const academic = String(params.academic || "Средняя успеваемость");
    const behavior = String(params.behavior || "Спокойный, дисциплинированный");
    const social = String(params.social || "В классе общителен, имеет друзей");
    const additional = String(params.additional || "");

    systemPrompt = `Ты — квалифицированный педагог-психолог и классный руководитель общеобразовательной школы Казахстана.
Ты составляешь официальную психолого-педагогическую характеристику на учащегося, полностью соответствующую требованиям районных отделов образования, ПМПК и комиссий по делам несовершеннолетних.`;

    userPrompt = `Составь официальную психолого-педагогическую характеристику:
- ФИО учащегося: ${studentName}
- Класс: ${grade}
- Цель составления / Куда предоставляется: ${purpose}
- Учебная деятельность: ${academic}
- Поведение и дисциплина: ${behavior}
- Взаимоотношения с коллективом и взрослыми: ${social}
${additional ? `- Дополнительные сведения: ${additional}` : ""}

Обязательные разделы характеристики:
1. Общие анкетные данные учащегося.
2. Состав семьи и условия воспитания.
3. Особенности познавательной сферы (внимание, память, мышление, темп деятельности).
4. Отношение к учебной деятельности и успеваемость по предметам.
5. Особенности личности и характера (эмоционально-волевая сфера, самооценка).
6. Взаимоотношения с одноклассниками и педагогами.
7. Внеурочная занятость, интересы, склонности.
8. Заключение и психолого-педагогические рекомендации для дальнейшей работы.

Стиль изложения — корректный, объективный, научный, доброжелательный.`;

  } else if (tool === "homeroom") {
    const topic = String(params.topic || "Безопасность в цифровой среде и профилактика буллинга");
    const grade = String(params.grade || "8 класс");
    const quarter = String(params.quarter || "2 четверть");
    const agendaCustom = String(params.agendaCustom || "");

    systemPrompt = `Ты — опытный классный руководитель и методист воспитательной работы в школе Казахстана.
Ты готовишь исчерпывающий пакет документов для проведения родительского собрания в соответствии с программой воспитания «Біртұтас тәрбие» РК.`;

    userPrompt = `Подготовь полный пакет материалов к родительскому собранию:
- Класс: ${grade}
- Четверть: ${quarter}
- Тема собрания: ${topic}
${agendaCustom ? `- Дополнительные вопросы: ${agendaCustom}` : ""}

Пакет должен содержать 4 готовых документа:
1. Повестка дня родительского собрания (с регламентом времени).
2. Выступление классного руководителя (полный текст доклада на 5–7 минут: доступный, убедительный, с практическими советами родителям).
3. Памятка для родителей (краткие правила и рекомендации в виде списка «Что делать / Чего избегать»).
4. Готовый Протокол родительского собрания (с графами: присутствовали, повестка, слушали, постановили / решения собрания).

Каждый раздел выдели чётким заголовком в Markdown.`;

  } else if (tool === "iom") {
    const studentName = String(params.studentName || "Учащийся");
    const subject = String(params.subject || "Математика");
    const grade = String(params.grade || "6 класс");
    const trackType = String(params.trackType || "Ликвидация пробелов в знаниях (слабоуспевающий)");
    const gaps = String(params.gaps || "Действия с обыкновенными и десятичными дробями, решение текстовых задач");
    const period = String(params.period || "1 месяц (4 недели)");

    systemPrompt = `Ты — ведущий педагог-методист по индивидуализации образовательного процесса в школах РК.
Ты составляешь Индивидуальный образовательный маршрут (ИОМ) учащегося по ликвидации пробелов или развитию одарённости.`;

    userPrompt = `Составь подробный Индивидуальный образовательный маршрут (ИОМ):
- Учащийся: ${studentName}
- Предмет: ${subject}
- Класс: ${grade}
- Направленность маршрута: ${trackType}
- Выявленные пробелы / Западающие темы: ${gaps}
- Срок реализации: ${period}

Структура документа:
1. Пояснительная записка: цель, задачи, ожидаемый результат.
2. Диагностическая карта затруднений учащегося.
3. Понедельный план работы (4 недели):
   - Неделя 1-4: Тема ликвидации пробела, цели обучения, формы работы (индивидуальная консультация, тренажёр, парная работа), конкретные дидактические задания.
4. Система контроля и промежуточной диагностики (тесты, карточки ФО).
5. Рекомендации родителям по поддержке ученика дома.
6. Критерии успешности завершения маршрута.

Форматируй в структурированный Markdown.`;

  } else {
    return NextResponse.json({ error: "Неизвестный инструмент" }, { status: 400 });
  }

  try {
    const completion = await executeWithFallback("enhance", async (client, model) => {
      const response = await client.chat.completions.create({
        model,
        temperature: 0.3,
        messages: [
          { role: "system", content: systemPrompt },
          { role: "user", content: userPrompt },
        ],
      });
      return response.choices[0]?.message?.content || "";
    });

    return NextResponse.json({
      ok: true,
      result: completion,
      tool,
    });
  } catch (error) {
    return NextResponse.json(
      { error: error instanceof Error ? error.message : "Не удалось сгенерировать документ" },
      { status: 500 },
    );
  }
}
